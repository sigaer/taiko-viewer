#!/usr/bin/env python3
"""Frozen synthetic image oracle -> installed center Viewer rendering, no network/SQL."""
import argparse
import hashlib
import importlib.util
import json
from pathlib import Path
import runpy
import sys

CANDIDATE = Path('/var/tmp/taiko-final-ownership-20261015/taiko')
ASSETS = Path('/var/tmp/taiko-phase2fe-20261014/assets')
BASELINES = {'b30': 'taiko-b30-20261014', 'personal': 'taiko-display-20261015',
             'progress': 'taiko-progress-20261014', 'trend': 'taiko-trend-20261015',
             'recommendation': 'taiko-phase2fe-20261014'}
PRODUCTS = ('taiko_bot', 'taiko_store', 'taiko_application', 'sakura_taiko_core', 'sakura_taiko_contract', 'runtime_memory')

def sha(path):
    h = hashlib.sha256()
    with path.open('rb') as stream:
        for chunk in iter(lambda: stream.read(65536), b''):
            h.update(chunk)
    return h.hexdigest()

def origins():
    output = {}
    root = Path(sys.prefix).resolve()
    for name in PRODUCTS:
        spec = importlib.util.find_spec(name)
        assert spec and spec.origin and Path(spec.origin).resolve().is_relative_to(root), 'product escaped installed environment'
        output[name] = spec.origin
    for name, module in list(sys.modules.items()):
        if any(name == prefix or name.startswith(prefix + '.') for prefix in PRODUCTS):
            filename = getattr(module, '__file__', None)
            if filename:
                assert Path(filename).resolve().is_relative_to(root), 'loaded product source fallback'
    return output

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--family', choices=tuple(BASELINES), required=True)
    parser.add_argument('--work', type=Path, required=True)
    args = parser.parse_args()
    assert sys.flags.isolated == 1
    work = args.work.resolve()
    assert work.is_relative_to('/var/tmp') and not work.exists(), 'new isolated fixture root required'
    work.mkdir(mode=0o700)
    baseline = Path('/var/tmp') / BASELINES[args.family] / 'baseline-center' / 'taiko'
    harness = CANDIDATE / 'tests/viewer/render_parity.py'
    fixture = CANDIDATE / 'tests' / args.family / 'events.py'
    freeze = CANDIDATE / 'tests/recommendation/freeze.py'
    inputs = [harness, fixture, freeze, CANDIDATE / 'packages/taiko-application/tests/fixture.py']
    inputs += sorted(baseline.rglob('*.py'))
    # Existing approved public renderer assets only; all userdata is generated by fixtures.
    public_assets = sorted(path for path in ASSETS.rglob('*') if path.is_file())
    report = {'status': 'FAIL', 'family': args.family, 'role': 'center', 'coreVersion': '0.1.1',
              'interpreter': sys.executable, 'productionAccess': False,
              'fixtureHashes': [{'file': str(path), 'sha256': sha(path)} for path in inputs],
              'publicAssetHashes': [{'file': str(path.relative_to(ASSETS)), 'sha256': sha(path)} for path in public_assets],
              'scope': 'Exact PNG SHA comparison to frozen source oracle under synthetic inputs/public assets. Existing harness mocks only declared transport/storage/catalog boundaries; not production E2E or all Bot rendering.',
              'oracleBoundary': 'Original test harness adds its fixture and generated frozen oracle paths; product origins must remain installed. Original harness/oracle/wheel are unchanged.'}
    try:
        report['originsBefore'] = origins()
        spec = importlib.util.spec_from_file_location('freeze', freeze)
        module = importlib.util.module_from_spec(spec)
        sys.modules['freeze'] = module
        spec.loader.exec_module(module)
        sys.argv = [str(harness), '--family', args.family, '--representative', '--host', 'center',
                    '--baseline', str(baseline), '--work', str(work), '--assets', str(ASSETS), '--application', str(CANDIDATE)]
        ns = runpy.run_path(str(harness), run_name='__main__')
        report['originsAfter'] = origins()
        report['pngGoldens'] = []
        for name, before, after in ns['cases']:
            expected, actual = ns['digest'](before()), ns['digest'](after())
            assert expected == actual, name + ' PNG SHA mismatch'
            report['pngGoldens'].append({'case': name, 'frozenSha256': expected, 'installedSha256': actual})
        report['status'] = 'PASS_SYNTHETIC_FROZEN_PNG_PARITY'
    finally:
        (work / 'image-golden-evidence.json').write_text(json.dumps(report, ensure_ascii=False, indent=2) + '\n')
        print(json.dumps({'status': report['status'], 'family': args.family, 'evidence': str(work / 'image-golden-evidence.json')}))

if __name__ == '__main__':
    main()
