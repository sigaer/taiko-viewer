#!/usr/bin/env python3
"""Crop numbered title plates using the existing top-slice rule (remove 45px).

Run through scripts/memory/run_qa.sh. Existing nine reviewed slices are retained
byte-for-byte, including the character-free 41/42/43 variants. Source artwork
stays outside this repository; only cropped web assets and metadata are emitted.
"""
import argparse
import hashlib
import json
from pathlib import Path
import re

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
LEGACY = {0, 1, 2, 41, 42, 43, 59, 60, 61}
USAGE = {
    0: ("clear", "unspecified"), 1: ("all_perfect", "unspecified"), 2: ("full_combo", "unspecified"),
    41: ("clear", "oni"), 42: ("full_combo", "oni"), 43: ("all_perfect", "oni"),
    59: ("clear", "inner_oni"), 60: ("full_combo", "inner_oni"), 61: ("all_perfect", "inner_oni"),
}


def digest(path):
    with path.open("rb") as stream:
        return hashlib.file_digest(stream, "sha256").hexdigest()


def generate(source, output, metadata, check):
    inputs = sorted((p for p in source.glob("name_plate_*.png") if re.fullmatch(r"name_plate_\d+\.png", p.name)),
                    key=lambda p: int(p.stem.split("_")[-1]))
    if not 1 <= len(inputs) <= 256:
        raise ValueError("Missing or oversized source plate catalog")
    output.mkdir(parents=True, exist_ok=True)
    items, table = [], []
    for path in inputs:
        plate_id = int(path.stem.split("_")[-1])
        target = output / f"name_plate_{plate_id}_slice.png"
        with Image.open(path) as original:
            if original.width not in {555, 556} or not 90 <= original.height <= 200:
                raise ValueError(f"Unexpected dimensions: {path.name}")
            if plate_id in LEGACY:
                # These tracked slices predate the full catalog. Do not replace
                # their reviewed variants with similarly named source artwork.
                with Image.open(target) as retained:
                    width, height = retained.size
                if (width, height) != (556, 45 if plate_id <= 2 else 71):
                    raise ValueError(f"Unexpected legacy slice: {plate_id}")
            else:
                cropped = original.crop((0, 0, original.width, original.height - 45))
                try:
                    width, height = cropped.size
                    if check:
                        with Image.open(target) as existing:
                            equal = existing.size == cropped.size and hashlib.sha256(existing.convert("RGBA").tobytes()).digest() == hashlib.sha256(cropped.convert("RGBA").tobytes()).digest()
                        if not equal:
                            raise ValueError(f"Stale slice: {plate_id}")
                    else:
                        cropped.save(target, optimize=True)
                finally:
                    cropped.close()
        # Leave room for characters/trophies on the right of decorated plates.
        art = 467 if plate_id in {59, 60, 61} else (430 if height > 45 and plate_id not in {41, 42, 43} else None)
        band = {"top": height - 41, "bottom": height - 3, "art": art}
        item = {"plateId": plate_id, "sourceFile": f"assets/name_plate/{path.name}",
                "outputFile": f"/assets/my-don/title-plate-slices/{target.name}",
                "width": width, "height": height, "textBand": band, "sha256": digest(target),
                "retainedLegacySlice": plate_id in LEGACY}
        if plate_id in USAGE:
            requirement, scope = USAGE[plate_id]
            item["usage"] = {"requirementType": requirement, "difficultyScope": scope}
        items.append(item)
        table.append(f"  {{ id: {plate_id}, width: {width}, height: {height}, top: {band['top']}, bottom: {band['bottom']}, art: {'null' if art is None else art} }},")
    manifest = {"cropRule": {"mode": "top_slice", "removeBottomPx": 45,
                             "description": "Top slice; retain the nine previously reviewed web variants."}, "items": items}
    files = {
        output / "manifest.json": json.dumps(manifest, ensure_ascii=False, indent=2) + "\n",
        metadata: "// Generated by scripts/generate_title_plate_slices.py; do not edit by hand.\nexport const TITLE_PLATE_SLICES = [\n" + "\n".join(table) + "\n] as const;\n",
    }
    for path, content in files.items():
        if check:
            if path.read_text() != content:
                raise ValueError(f"Stale metadata: {path.name}")
        else:
            path.write_text(content)
    print(json.dumps({"plates": len(items), "retained": len(LEGACY), "generated": len(items) - len(LEGACY), "check": check}))


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, default=Path("/home/sigaer/taiko/assets/name_plate"))
    parser.add_argument("--output", type=Path, default=ROOT / "public/assets/my-don/title-plate-slices")
    parser.add_argument("--metadata", type=Path, default=ROOT / "utils/ds/titlePlateSlices.ts")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    generate(args.source, args.output, args.metadata, args.check)
